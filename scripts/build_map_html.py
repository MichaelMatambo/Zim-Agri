"""Builds constants/mapHtml.ts: one self-contained HTML page (Leaflet + our map script) for the WebView map.
Needs leaflet.js / leaflet.css (npm pack leaflet@1.9.4). Usage: python3 scripts/build_map_html.py <dir containing leaflet.js and leaflet.css>"""
import json, sys
d = sys.argv[1] if len(sys.argv) > 1 else "."
js = open(f"{d}/leaflet.js", encoding="utf-8").read(); css = open(f"{d}/leaflet.css", encoding="utf-8").read()
app = open("scripts/map_app.js", encoding="utf-8").read()
extra = """html,body,#map{height:100%;margin:0;padding:0;background:#DCE6EA}
.tn{background:transparent;border:0;box-shadow:none;font:800 10px sans-serif;color:#2b2b2b;padding:0}
.leaflet-tooltip-right:before,.leaflet-tooltip-left:before{display:none}
.leaflet-top.leaflet-left{top:112px}
.leaflet-control-zoom a{width:34px;height:34px;line-height:34px;font-size:20px}
.leaflet-popup-content{font:12px sans-serif;margin:10px 12px}"""
assert "</script" not in js and "</script" not in app
html = f'<!doctype html><html><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1,maximum-scale=1,user-scalable=no"><style>{css}\n{extra}</style></head><body><div id="map"></div><script>{js}</script><script>{app}</script></body></html>'
open("constants/mapHtml.ts", "w", encoding="utf-8").write("// AUTO-GENERATED by scripts/build_map_html.py (Leaflet 1.9.4 + scripts/map_app.js). Do not edit by hand.\nexport const MAP_HTML = " + json.dumps(html) + ";\n")
print("mapHtml.ts", len(html)//1024, "KB")
